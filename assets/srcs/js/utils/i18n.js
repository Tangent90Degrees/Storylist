let locale = 'en'

export const t = key =>
    translations[locale]?.[key] ?? translations.en[key] ?? key

export const setLocale = lang => { if (translations[lang]) locale = lang }
export const getLocale = () => locale
export const toggleLocale = () => {
    locale = locale === 'en' ? 'zh' : 'en'
    return locale
}
