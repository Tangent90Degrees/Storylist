#!/usr/bin/env python3
"""
Bundle downloaded SVG icon files into a single ES module so <wa-icon> can
render icons with zero network requests.

Output: assets/srcs/js/data/icon-svgs.js
"""

import os
import re
import json

def parse_svg(content):
    """Return (viewBox, inner_paths) extracted from an SVG file."""
    vb = re.search(r'viewBox="([^"]+)"', content)
    viewBox = vb.group(1) if vb else "0 0 512 512"
    # Strip everything except the inner shape elements
    inner = content
    inner = re.sub(r'<\?xml[^>]*>\s*', '', inner)
    inner = re.sub(r'<!DOCTYPE[^>]*>\s*', '', inner)
    inner = re.sub(r'<!--.*?-->', '', inner, flags=re.DOTALL)
    inner = re.sub(r'<svg[^>]*>', '', inner)
    inner = re.sub(r'</svg>', '', inner)
    inner = inner.strip()
    return viewBox, inner


def load_dir(style_dir):
    icons = {}
    if not os.path.isdir(style_dir):
        return icons
    for fname in sorted(os.listdir(style_dir)):
        if not fname.endswith(".svg"):
            continue
        name = fname[:-4]
        with open(os.path.join(style_dir, fname), "r", encoding="utf-8") as f:
            content = f.read()
        viewBox, inner = parse_svg(content)
        icons[name] = (viewBox, inner)
    return icons


def js_string(s):
    """Escape a string for use inside a JS template literal (backticks)."""
    s = s.replace("\\", "\\\\")
    s = s.replace("`", "\\`")
    s = s.replace("${", "\\${")
    return s


def main():
    root = os.path.join(os.path.dirname(__file__), "..", "assets")
    solid = load_dir(os.path.join(root, "icons", "solid"))
    regular = load_dir(os.path.join(root, "icons", "regular"))

    out_path = os.path.join(root, "srcs", "js", "data", "icon-svgs.js")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by scripts/bundle-icons.py — DO NOT EDIT\n")
        f.write("// Source: Font Awesome 6 Free — https://fontawesome.com\n")
        f.write("// License: CC BY 4.0 — https://creativecommons.org/licenses/by/4.0/\n")
        f.write("// Each icon: { v: viewBox, p: inner SVG path markup }\n\n")
        f.write("export const ICON_SVGS = {\n")

        f.write("  solid: {\n")
        for name, (vb, p) in sorted(solid.items()):
            f.write(f"    {json.dumps(name)}: {{ v: {json.dumps(vb)}, p: `{js_string(p)}` }},\n")
        f.write("  },\n")

        f.write("  regular: {\n")
        for name, (vb, p) in sorted(regular.items()):
            f.write(f"    {json.dumps(name)}: {{ v: {json.dumps(vb)}, p: `{js_string(p)}` }},\n")
        f.write("  },\n")
        f.write("}\n")

    print(f"Wrote {len(solid)} solid + {len(regular)} regular icons -> {out_path}")


if __name__ == "__main__":
    main()
